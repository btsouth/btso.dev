export type Shape = { cols: number; lit: [number, number][] };

/** Lit pixel coordinates for a line of text, or null if a character is missing. */
export function textShape(text: string): Shape | null {
  const lit: [number, number][] = [];
  let x = 0;
  for (const ch of text) {
    const glyph = G[ch] ?? G[ch.toUpperCase()];
    if (!glyph) return null;
    const rows = glyph.split(' ');
    rows.forEach((row, y) => [...row].forEach((c, dx) => { if (c === '#') lit.push([x + dx, y]); }));
    x += rows[0].length + 1;
  }
  return { cols: Math.max(0, x - 1), lit };
}
